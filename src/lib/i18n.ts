const translations: Record<AppLanguage, Record<string, string>> = { 'zh-CN': zhCN, en }

export function translate(language: AppLanguage, key: string, params: TranslationParams = {}): string {
  const template = translations[language][key] || zhCN[key] || key
  return template.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match))
}

export function useI18n(): { language: AppLanguage; locale: string; t: Translate } {
  const language = useStore((state) => state.language)
  const t = useCallback<Translate>((key, params) => translate(language, key, params), [language])
  return { language, locale: language === 'en' ? 'en-US' : 'zh-CN', t }
}
